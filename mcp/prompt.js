/* ═══════════════════════════════════════════════════════════
   prompt.js — Prompt Técnico Maestro (solo isométrico)
   Fuente única de verdad del contrato que el LLM debe seguir
   para generar ilustraciones isométricas parseables por js/parser.js.
   Entradas: boceto y referencia opcionales (la referencia puede NO
   ser isométrica: se transpone) o solo una indicación de texto.
   Compartido por: MCP stdio, MCP HTTP y el mock del navegador.
   ═══════════════════════════════════════════════════════════ */

/**
 * @param {object} entradas
 * @param {string} [entradas.sketch]  etiqueta del boceto (estructura, opcional)
 * @param {string} [entradas.ref]     etiqueta de la referencia (estilo y/o forma, opcional; no hace falta que sea isométrica)
 * @param {string} [entradas.hint]    indicación del usuario (objetos, paleta, estilo, texto libre)
 * @returns {string} prompt completo en texto plano
 */
export function buildPrompt({ sketch, ref, hint } = {}) {
  const hasRef = Boolean(ref);
  const lines = [
    `# PROMPT TÉCNICO MAESTRO — CSSketch (isométrico)`,
    ``,
    `## Entradas`,
    `- Boceto (estructura): ${sketch || '(no hay boceto)'}`,
    `- Referencia (estilo y forma): ${ref || '(no hay referencia: diseña desde la indicación)'}`,
  ];

  if (hint) {
    lines.push(`- Indicación: ${hint}`);
  }

  lines.push(
    ``,
    `## Rol`,
    `Actúa como ilustrador isométrico técnico. Solo produces ilustraciones isométricas.`,
    `Tu salida es UN ÚNICO documento HTML autocontenido: un bloque <style> seguido de marcado`,
    `HTML con un <svg> inline. Sin dependencias, sin frameworks, sin JavaScript, sin imágenes`,
    `externas, sin <link>. Nada de perspectiva, nada de vistas frontales ni cenitales.`,
    ``,
    `## Modo de entrada (decídelo antes de dibujar)`,
    `- Referencia isométrica: réplica exacta (ver "Fidelidad de réplica").`,
    `- Referencia NO isométrica (foto, perspectiva, vista frontal, flat 2D, dibujo libre):`,
    `  1. Lista los objetos de la referencia y sus relaciones (qué está encima, qué atraviesa qué).`,
    `  2. Reconstruye cada objeto como sólido en el canon isométrico de abajo. Las proporciones`,
    `     salen de la referencia; la proyección NUNCA sale de ella.`,
    `  3. Toma paleta y estilo de línea de la referencia (monocromo, flat-tone...).`,
    `  4. Si una cara no se ve en la referencia, deduce la forma más simple (caja, cilindro).`,
    `- Sin referencia (solo texto): define primero la lista de objetos (una línea cada uno),`,
    `  luego compón la escena isométrica: objetos agrupados en un volumen compacto, centrado,`,
    `  con ejes W vertical y U/V de suelo. Paleta y estilo salen de la indicación o, por defecto,`,
    `  line-art monocromo.`,
    `Modo actual: ${hasRef ? 'referencia (verifica si es isométrica)' : 'solo texto'}.`,
    ``,
    `## Sistema de variables obligatorio`,
    `Declara TODOS los parámetros editables dentro de :root, cada uno con un comentario semántico`,
    `que la UI usará para construir los controles:`,
    ``,
    `  /*type:color*/ --ink: #111111;`,
    `  /*type:color*/ --paper: #ffffff;`,
    `  /*type:range|min:1|max:8|step:0.5|unit:px*/ --bw: 3;`,
    `  /*type:range|min:-30|max:30|step:1|unit:px*/ --lens-dy: 0;`,
    `  /*type:select|options:line-art|flat-tone*/ --style: line-art;`,
    `  /*type:text*/ --caption: "Búsqueda";`,
    ``,
    `Reglas de la sintaxis de comentario:`,
    `  - type:color  → color plano (hex de 6 dígitos).`,
    `  - type:range  → numérico. Opcionales min, max, step y unit (px|%|deg|rem|vh).`,
    `                   El valor en :root es NUMÉRICO puro; la unit se aplica al usarlo.`,
    `  - type:select → lista de opciones separadas por "|".`,
    `  - type:text   → cadena libre.`,
    `  - Agrupa por prefijo de nombre (--obj-*, --ink-*, --style-*) para las secciones.`,
    `  - Usa calc(var(--x) * 1px) para cada medida y expón la altura y la extrusión de cada objeto.`,
    ``,
    `## Arquitectura de estilos (obligatoria; CSS nativo en UN solo <style>)`,
    `Sin preprocesador ni framework: el orden de escritura del <style> ES el orden de cascada.`,
    `Escribe las secciones en este orden, cada una con su comentario /*── … ──*/:`,
    `  1. :root        — ÚNICO lugar del documento con literales (color, medida, opacidad).`,
    `  2. base         — html/body, reset mínimo, tipografía por etiqueta.`,
    `  3. escena       — .scene, svg, capas, fondo.`,
    `  4. trazos/tonos — .ln, .ink, .mark, .thin y los tonos de cara.`,
    `  5. piezas       — clases de objeto (.lens, .handle …).`,
    `  6. utilidades   — modificadores puntuales.`,
    `Capa de tokens (DRY):`,
    `  - Fuera de :root NO hay literales: toda regla consume var(--x) o calc(var(--x) * 1unit).`,
    `  - Un valor se declara UNA sola vez. Si dos variables repiten el mismo hex, una lleva el`,
    `    literal y la otra apunta con var(--otra).`,
    `  - Nombres por ROL semántico (--ink, --tone-top, --lens-dy), nunca paleta cruda (--gray-100).`,
    `  - Los tres tonos de cada sólido salen de tokens (--tone-top / --tone-side / --tone-dark o su`,
    `    equivalente), nunca de hex sueltos en las clases.`,
    `Clases y selectores:`,
    `  - Cada clase, UNA responsabilidad: .ln trazo+relleno, .ink relleno, .mark/.thin trazos,`,
    `    tonos por cara. La apariencia va en la clase de la pieza o en un modificador; prohibido`,
    `    selectores por ubicación (.scene .lupa .aro {}).`,
    `  - Los id del marcado (g#bar-1) son estructurales: NUNCA se estilizan con #id en CSS.`,
    `  - Sin !important: la cascada se ordena, no se fuerza.`,
    `Accesibilidad:`,
    `  - Texto dibujado (--caption o <text>): contraste ≥4.5:1 sobre su fondo (WCAG 1.4.3).`,
    `  - Tinta contra papel (contorno y relleno): ≥4.5:1; cubre el ≥3:1 de figuras (WCAG 1.4.11).`,
    `  - Sin animaciones; si existen, anímalas dentro de @media (prefers-reduced-motion: reduce).`,
    ``,
    `## ORDEN DE CAPAS (prioridad máxima: decídelo ANTES de escribir marcado)`,
    `El orden de pintado decide qué se ve. Razona como un grafo de oclusión, no a ojo:`,
    `1. INVENTARIO: lista cada pieza visible (una línea: nombre, objeto al que pertenece).`,
    `2. PARES SOLAPADOS: para cada par que se toca, escribe "A tapa a B porque ..." o "A y B no se solapan".`,
    `   Si una pieza atraviesa otra, escribe "A cruza B: recorte con clipPath en B" y resuélvelo así.`,
    `3. ORDEN Z (atrás → delante): ordena las piezas respetando los pares. Reglas de desempate:`,
    `   a) fondo y decoración suelta primero;`,
    `   b) sombras de suelo antes que los objetos que proyectan;`,
    `   c) en cada sólido: caras laterales → tapa → detalles sobre la cara;`,
    `   d) piezas cercanas al espectador (mayor x+y en el suelo) al final.`,
    `4. EMITE EL PLAN como comentario HTML justo antes del <svg>:`,
    `   <!-- Z (atrás → delante): 1 decoración · 2 burbuja · 3 barras · 4 mango · 5 lupa · 6 teclas`,
    `        Oclusión: 5 tapa a 4 (el aro cubre el arranque del mango). -->`,
    `5. MARCA CADA GRUPO con data-z="n" en el mismo orden ascendente del DOM. Nada se reordena después.`,
    `6. AUTOCOMPROBACIÓN: recorre la lista de atrás hacia delante y confirma que cada pieza tapa lo que debe.`,
    `   Si una pieza debería tapar a otra y no lo hace, el data-z está mal: corrígelo, no añadas parches.`,
    ``,
    `## Canon isométrico (obligatorio)`,
    `Toda la escena vive en una proyección isométrica REAL.`,
    ``,
    `0. CUADRÍCULA BASE (obligatoria): dos familias de líneas a +30° y −30° respecto a la horizontal,`,
    `   más verticales. Ambos lados, sin excepción. Tangente de 30° = 0.577, por eso U y V tienen`,
    `   componente vertical de 0.5 y horizontal de 0.866 (unidades del viewBox, y hacia abajo es positivo).`,
    `   Cada vértice cae en la retícula: P = O + i·G·U + j·G·V + k·G·W, con i, j, k enteros y G el paso`,
    `   (p. ej. G = 10). Si una coordenada no cae en la retícula, corrígela antes de escribir el marcado.`,
    `   Círculo en el suelo = elipse con ry/rx = 0.577 (rx=92 → ry=53). Nunca ry/rx = 0.65.`,
    `   Cada celda rómica de la retícula admite su círculo inscrito: radio G·√3/4 ≈ 0.433·G, tangente`,
    `   a los puntos medios de sus aristas (en el suelo se dibuja como elipse ry/rx = 0.577). Ese`,
    `   círculo es el MÓDULO DE REDONDEO de la escena: de él salen los radios de filete R = G·k`,
    `   (k ∈ {0.25, 0.5}), los botones sobre caras y las islas redondas. Úsalo, no inventes radios sueltos.`,
    `1. TRES EJES (unidades del viewBox, y hacia abajo es positivo):`,
    `     U = ( 0.866, -0.5)   eje "largo" (atrás-derecha)`,
    `     V = (-0.866, -0.5)   eje "ancho" (atrás-izquierda)`,
    `     W = ( 0,     -1)     eje altura (vertical puro)`,
    `   Toda arista es paralela a U, V o W. Las verticales NUNCA se inclinan.`,
    `2. CAJAS POR ESQUINAS. Caja L×A×H con esquina inferior frontal P0=(x,y):`,
    `     P1 = P0 + U·L     P2 = P1 + W·H     P3 = P0 + W·H`,
    `     Q1 = P1 + V·A     Q2 = Q1 + W·H     Q3 = P3 + V·A`,
    `   Caras visibles: tapa (P3, P2, Q2, Q3 en orden de rombo), derecha (P0, P1, P2, P3) e`,
    `   izquierda (P0, P0+V·A, Q3, P3). Escribe los polígonos con estos puntos EXACTOS.`,
    `3. TRES TONOS por sólido, iguales en toda la escena: top = más claro · una lateral = medio ·`,
    `   la otra = más oscuro. La luz viene siempre del mismo lado (según la referencia).`,
    `4. DETALLES SOBRE LA CARA. Botón, pantalla, ranura o logo se dibuja dentro de un <g> con`,
    `   transform="matrix(a,b,c,d,ox,oy)" que mapea el plano de la cara a pantalla:`,
    `     cara top:            matrix(0.866,-0.5,-0.866,-0.5, ox, oy)`,
    `     cara izquierda:      matrix(0.866,-0.5, 0,-1,       ox, oy)`,
    `     cara derecha:        matrix(-0.866,-0.5, 0,-1,      ox, oy)`,
    `   Dentro del <g> dibujas la forma plana (rect con rx, círculo, path). Nada de border-radius.`,
    `5. REDONDEOS Y FILETES (obligatorio; nada de siluetas a 90° vistas de canto). Radio constante`,
    `   en toda la escena: R = G·k con k ∈ {0.25, 0.5} (o ≈3–6% del lado mayor), declarado como`,
    `   token (p. ej. /*type:range|…|unit:px*/ --r: 2.5) y consumido con calc(var(--r) * 1px).`,
    `   a. Cara plana = <rect> con rx dentro de la matriz de su plano:`,
    `        <g transform="matrix(0.866,-0.5,-0.866,-0.5, ox, oy)">`,
    `          <rect x="…" y="…" width="…" height="…" rx="calc(var(--r) * 1px)"/>`,
    `      r, rx y ry van como PROPIEDADES CSS con calc(var(--…)) para que el filete sea paramétrico.`,
    `   b. Silueta poligonal: cada esquina P entre aristas hacia A y B se sustituye por los dos`,
    `      puntos tangentes P + t·u y P + t·v unidos por arco "A R R 0 0 s x y"`,
    `      (t = R·tan(θ/2); en una esquina de 90° en la cara, t = R; el barrido s gira hacia el`,
    `      interior de la cara). Los puntos tangentes caen SOBRE las aristas existentes: la esquina`,
    `      no se deforma, se redondea.`,
    `   c. Arista vertical redondeada = CÁPSULA: silueta de dos semicírculos unidos por tangentes`,
    `      (rect con rx = altura/2 en el plano correspondiente).`,
    `   d. Cilindros y discos ya son círculos en planos (regla 6): apóyalos siempre en la retícula.`,
    `   e. stroke-linejoin:round NO redondea la silueta: el radio vive en la geometría, en el path`,
    `      o en el rx, nunca solo en el trazo.`,
    `6. CÍRCULOS EN CUALQUIER PLANO: un círculo de radio r se escribe como matrix() con las imágenes`,
    `   de los dos ejes de su plano, multiplicadas por r:`,
    `     plano del suelo (U,V):   matrix(0.866r,-0.5r,-0.866r,-0.5r, x, y)  → elipse ry/rx = 0.577`,
    `     plano U-W (eje del tubo -V): matrix(0.866r,-0.5r, 0,-r, x, y)`,
    `     plano V-W (eje del tubo U):  matrix(-0.866r,-0.5r, 0,-r, x, y)`,
    `   Tubo/mango: silueta = dos líneas paralelas al eje, tangentes a la elipse de la tapa (ver Z4 del`,
    `   ejemplo). NUNCA un rect rotado ni un elipse con rotate(). Usa vector-effect="non-scaling-stroke"`,
    `   en las tapas para que el trazo quede uniforme.`,
    `7. SOMBRA PROYECTADA: paralelogramo en el plano de apoyo (solo U y V, cero W), relleno plano`,
    `   casi negro o tinta de la paleta, sin blur ni gradiente.`,
    `8. APILADOS Y EXPLOSIONADOS: componentes alineados en (x,y), apilados en W con huecos constantes;`,
    `   la tapa de uno marca la base del siguiente.`,
    `9. GIRO DE PIEZAS: solo en pasos de 60° sobre el plano del suelo. Una pieza girada se dibuja`,
    `   con los puntos calculados, nunca con rotate() sobre un rectángulo.`,
    ``,
    `## Volúmenes curvos y cortes (método caja → círculo → recorte)`,
    `Todo volumen curvo se construye igual que en un dibujo técnico: PRIMERO la caja que lo`,
    `contiene, DESPUÉS el círculo, AL FINAL el recorte. Nunca traces una curva "a ojo":`,
    `1. DELIMITA: inscribe el volumen en su prisma de la retícula (las cajas ya las dominas).`,
    `   El ancho y la profundidad del prisma son el diámetro del círculo que va dentro.`,
    `2. CENTRA: el centro del círculo cae en un nudo de la retícula (o en el punto medio de una`,
    `   arista de la celda). De ahí el radio R = lado/2. Círculo en el suelo = elipse ry/rx = 0.577;`,
    `   en cara lateral = matrix(0.866r,−0.5r, 0,−r) o matrix(−0.866r,−0.5r, 0,−r).`,
    `3. DIBUJA COMPLETO y recorta después: el cilindro/círculo se escribe entero y las partes que`,
    `   quedan dentro de la unión se quedan; lo que sobra se elimina con clipPath o uniendo solo`,
    `   los tramos visibles en el mismo path. En el plan de caras escribe: "dibujo el cilindro`,
    `   completo → sitúo el círculo del corte → selecciono los tramos que quedan".`,
    `4. FAMILIAS OBLIGATORIAS en tu banco de piezas (aplica las que el objeto pida, sin forzar):`,
    `   a. CILINDRO sobre prisma: prisma + tapa = elipse + pared de dos verticales tangentes y`,
    `      media elipse inferior. Se "pega" a la caja por su base.`,
    `   b. ARO / DISCO CON AGUJERO (donut plano): dos elipses concéntricas en el mismo plano; el`,
    `      agujero muestra el fondo a través (no lo rellenes).`,
    `   c. CASQUETE / MEDIA ESFERA: medio disco sobre el suelo + su elipse vista + vertical.`,
    `   d. SEMICÍRCULO Y MEDIA CAJA: mitad de círculo o de elipse unida a una caja recta (ranuras`,
    `      redondeadas, huecos en U, topes con testa redonda).`,
    `   e. TRONCO DE CONO: base = elipse grande, tapa = elipse pequeña, laterales = tangentes comunes`,
    `      a ambas elipses (no rectas sueltas).`,
    `   f. CÁPSULA / STADIO: rect con rx = altura/2 en el plano correspondiente (ya en canon 5c).`,
    `   g. SOBREPOSICIONES: cilindro atravesando una placa, caja sobre base redondeada, agujero`,
    `      cilíndrico pasando por dos caras (elipse de entrada y de salida alineadas en el eje).`,
    `5. CORTES VISIBLES: cuando un corte deja una arista viva, dibuja el filo (línea recta o arco`,
    `   según el corte). No dibujes líneas ocultas: la forma se entiende por sus aristas visibles.`,
    `6. CENTROS Y EJES: puedes marcar centros con una cruz fina de ejes (clase .thin) dentro del`,
    `   círculo — es la única decoración técnicamente honesta; úsala con moderación.`,
    ``,
    `## Estilos de línea (elige uno; por defecto line-art)`,
    `a) line-art: caras blancas, contorno negro uniforme, una sola cara con tramado de líneas`,
    `   paralelas a U o V para indicar sombra. Solo var(--ink) y var(--paper).`,
    `b) flat-tone: 3 tonos por sólido (mismas reglas de tono), contorno negro uniforme y sombra`,
    `   paralelogramo sólida. Paleta muestreada de la referencia o de la indicación.`,
    `Sin degradados, sin mask, sin blend, sin blur.`,
    ``,
    `## Construcción`,
    `1. PLAN DE CARAS. Antes del marcado escribe: extrusión global E (dx, dy) medida en el viewBox;`,
    `   por cada sólido, sus caras visibles (regla: cara visible ⟺ normal_exterior · E > 0).`,
    `2. UNA SILUETA, DOS CAPAS. Cada sólido es UNA <path> de silueta completa más la MISMA path`,
    `   trasladada por E debajo como cara lateral. Detalles internos se dibujan encima, recortados`,
    `   a la silueta con clipPath. No armes un sólido con varias formas de contorno propio.`,
    `3. BARRAS Y BRAZOS: dos capas (lateral trasladado E + tapa). Orden de pintado: primero TODAS las`,
    `   caras laterales, después TODAS las tapas, para no tener costuras.`,
    `4. OCCLUSIÓN. Escribe el z-order: qué tapa a cuál y por qué. Las formas que atraviesan otros`,
    `   objetos se recortan con <clipPath>, no se redibujan a ojo.`,
    `5. GEOMETRÍA COMPUTADA > ESTIMADA. Con 4+ aristas, calcula los puntos y escríbelos exactos.`,
    ``,
    `## Estructura del marcado`,
    `  .scene (position:relative; aspect-ratio:1/1; overflow:hidden)`,
    `    > svg (viewBox, width/height 100%)`,
    `      > g (grupos por objeto, con id)`,
    `      > g.lens / g.handle ... (transform con calc(var(--x) * 1px) para mover piezas en vivo)`,
    `    > div.grain (opcional, opacity: var(--grain))`,
    `  Clases SVG: .ln (trazo + relleno), .ink (relleno negro), .mark (trazo sin relleno), .thin (trazo fino).`,
    ``,
    `## Fidelidad de réplica (solo con referencia isométrica)`,
    `- MIDE antes de generar: posición de cada elemento en % del lienzo; ángulo de cada pieza;`,
    `  grosor de contorno (bw ≈ 1.2% del ancho); extrusión (|E| ≈ 3–6% del ancho); tamaños relativos.`,
    `- Respeta el mapa de posiciones dentro de ±2% del lienzo.`,
    `- NO reorganices la composición, NO añadas ni quites elementos. Réplica, no reinterpretación.`,
    `- Reproduce exactamente los solapamientos: qué borde pisa a cuál.`,
    ``,
    `## Restricciones de salida`,
    `  - Exactamente un bloque <style> en el head. Sin <link>, <script>, <img> ni url() externas.`,
    `  - Un <svg> inline con viewBox por escena. La geometría isométrica va en el svg.`,
    `  - Todas las medidas derivadas de variables vía calc(var(--x) * 1unit).`,
    `  - Ninguna regla con !important, ningún #id como selector de estilos y ningún literal`,
    `    (color, medida u opacidad) fuera de :root.`,
    `  - El marcado debe ser HTML válido con no menos de 60 nodos.`,
    `  - Comentarios de sección en CSS (/*── Lupa ──*/) para legibilidad.`,
    ``,
    `## Objetivo visual`,
    `Una ilustración isométrica limpia: volúmenes con caras claras, contorno uniforme, sin ruido.`,
    `Profundidad por tono de cara, no por sombras difusas.`
  );

  return lines.join('\n');
}

export default buildPrompt;
