/* ═══════════════════════════════════════════════════════════
   prompt.js — Prompt Técnico Maestro
   Fuente única de verdad del contrato que el LLM debe seguir
   para generar CSS Art parseable por js/parser.js.
   Compartido por: MCP stdio, MCP HTTP y el mock del navegador.
   ═══════════════════════════════════════════════════════════ */

/**
 * @param {object} entradas
 * @param {string} entradas.sketch  etiqueta del boceto (estructura)
 * @param {string} entradas.ref     etiqueta de la referencia (estilo)
 * @param {string} [entradas.hint]  indicación opcional del usuario
 * @returns {string} prompt completo en texto plano
 */
export function buildPrompt({ sketch, ref, hint }) {
  const lines = [
    `# PROMPT TÉCNICO MAESTRO — CSSketch`,
    ``,
    `## Entradas`,
    `- Estructura (boceto): ${sketch || '(sin archivo)'}`,
    `- Estilo (referencia): ${ref || '(sin archivo)'}`,
  ];

  if (hint) {
    lines.push(`- Indicación: ${hint}`);
  }

  lines.push(
    ``,
    `## Rol`,
    `Actúa como ilustrador técnico especializado en CSS Art de alta complejidad.`,
    `Tu salida es UN ÚNICO documento HTML autocontenido: un bloque <style> seguido`,
    `de marcado HTML. Sin dependencias, sin frameworks, sin JavaScript, sin imágenes`,
    `externas. Todo debe dibujarse con CSS puro y, cuando aporte, SVG embebido inline.`,
    ``,
    `## Sistema de variables obligatorio`,
    `Declara TODOS los parámetros editables dentro de :root, cada uno acompañado de`,
    `un comentario semántico que la UI usará para construir los controles:`,
    ``,
    `  /*type:color*/ --sky-top: #0b1d3a;`,
    `  /*type:range|min:0|max:100|step:1|unit:%*/ --horizon: 62;`,
    `  /*type:range|min:0|max:360|step:1|unit:deg*/ --sun-angle: 205;`,
    `  /*type:select|options:normal|screen|overlay|multiply*/ --blend-mode: screen;`,
    `  /*type:text*/ --caption: "Costa Norte";`,
    ``,
    `Reglas de la sintaxis de comentario:`,
    `  - type:color  → color plano (hex de 6 dígitos).`,
    `  - type:range  → numérico. Opcionales min, max, step y unit (px|%|deg|rem|vh).`,
    `                   El valor en :root es NUMÉRICO puro; la unit se aplica al usarlo.`,
    `  - type:select → lista de opciones separadas por "|".`,
    `  - type:text   → cadena libre.`,
    `  - Agrupa por prefijo de nombre (--sky-*, --hill-*, --sea-*) para las secciones.`,
    ``,
    `## Técnicas de construcción exigidas`,
    `1. Capas apiladas con position:absolute e inset fijo; escena con position:relative`,
    `   y overflow:hidden para que nada se salga del lienzo.`,
    `2. Gradientes complejos: linear-gradient con 4+ paradas, radial-gradient para`,
    `   resplandores y conic-gradient + repeating-conic-gradient para rayos, brillos`,
    `   y texturas de rayado.`,
    `3. clip-path con polygon() para siluetas orgánicas (colinas, olas, velas).`,
    `   mask-image / -webkit-mask-image con gradientes para desvanecer bordes.`,
    `4. Pseudo-elementos ::before y ::after en al menos 8 selectores distintos,`,
    `   usando content:"" + transform + filter para duplicar formas sin añadir nodos.`,
    `5. Múltiples box-shadows en una sola declaración (3+ sombras) para profundidad,`,
    `   neblina y contornos de luz.`,
    `6. SVG embebido con <defs>, <linearGradient>, <path>, <use> y filter (feGaussianBlur)`,
    `   para elementos que el CSS puro haría mal: aves, reflejos finos, espuma.`,
    `7. Variable CSS usada dentro de calc() y dentro de transform, de modo que moverla`,
    `   reposicione la pieza en tiempo real sin reflow de la estructura.`,
    `8. Mezcla de modos con mix-blend-mode leído desde una variable type:select.`,
    `9. Filtro de grano y viñeta como capa final, opacidad regulable por variable.`,
    `10. Responsive dentro del iframe: la escena usa aspect-ratio y clamp() para que`,
    `    el render funcione a cualquier tamaño de lienzo.`,
    ``,
    `## Estructura de capas mínima (mínimo 4 niveles de anidación)`,
    `  .scene > .sky > .sun > .sun__rays            (radial + conic)`,
    `  .scene > .sky > .clouds > .cloud > .cloud__puff  (pseudo-elementos)`,
    `  .scene > .terrain > .hill--far|mid|near > .hill__ridge (clip-path)`,
    `  .scene > .sea > .wave > .wave__foam          (mask + box-shadow)`,
    `  .scene > .cast > .boat > .boat__sail         (SVG use + gradientes)`,
    `  .scene > .overlay > .grain / .vignette       (mix-blend-mode)`,
    ``,
    `## Sistema tridimensional (obligatorio si la referencia es 3D/isométrica)`,
    `La referencia NO es "objetos con sombra desplazada": son sólidos con caras.`,
    `Construye geometría real, no trucos de box-shadow.`,
    ``,
    `### Canon isométrico (gramática de las referencias de ilustración iso)`,
    `Toda la escena vive en una proyección isométrica REAL. Reglas duras:`,
    ``,
    `1. RETÍCULA DE TRES EJES. Toda arista es paralela a uno de estos vectores`,
    `   (unidades del viewBox, y hacia abajo es positivo):`,
    `     U = ( 0.866, -0.5)   eje "largo" (hacia atrás-derecha)`,
    `     V = (-0.866, -0.5)   eje "ancho"  (hacia atrás-izquierda)`,
    `     W = ( 0,     -1)     eje altura (vertical puro)`,
    `   Las verticales NUNCA se inclinan; no hay convergencia de perspectiva.`,
    `2. CAJAS POR ESQUINAS CALCULADAS. Para caja L×A×H con esquina inferior`,
    `   frontal en P0=(x,y):`,
    `     P1 = P0 + U·L          P2 = P1 + W·H       P3 = P0 + W·H   (cara izq.)`,
    `     Q1 = P1 + V·A          Q2 = Q1 + W·H       Q3 = P3 + V·A   (cara der.)`,
    `     T1 = Q3                T2 = Q2              T3 = P3         (cara top)`,
    `   Escribe los polígonos con estos puntos EXACTOS. Tres caras visibles:`,
    `   top (rombo), frontal-izquierda y frontal-derecha (paralelogramos).`,
    `3. TRES VALORES DE TONO por sólido, iguales en toda la escena:`,
    `   top = más claro · una lateral = media · otra lateral = más oscura.`,
    `   La luz viene siempre del mismo lado (según la referencia).`,
    `4. DETALLES MAPEADOS AL PLANO DE LA CARA. Un botón, pantalla, ranura o`,
    `   logo sobre una cara se dibuja con un <g transform="matrix(...)"> que`,
    `   mapea el plano local de esa cara a screen:`,
    `     cara top:            matrix(0.866,-0.5, -0.866,-0.5, ox, oy)`,
    `     cara frontal-izq.:   matrix(0.866,-0.5,  0,-1,      ox, oy)`,
    `     cara frontal-der.:   matrix(-0.866,-0.5, 0,-1,      ox, oy)`,
    `   Dentro del <g> dibujas la forma plana tal cual (rect con rx, círculo,`,
    `   path). Así los detalles "pertenecen" a la cara y no flotan.`,
    `5. ESQUINAS REDONDEADAS: radio constante en toda la escena (≈2–4% del`,
    `   lado mayor). En isométrica el redondeo es un arco EN EL PLANO de la`,
    `   cara (se dibuja dentro del <g> matrix de la cara4). Prohibido`,
    `   border-radius de CSS sobre formas isométricas.`,
    `6. CILINDROS Y ELIPSES: círculo sobre la cara top → se dibuja como círculo`,
    `   dentro del matrix del top; botones/puertos laterales → círculos en el`,
    `   matrix de su cara lateral (salen como elipses estiradas, correctas).`,
    `   Las tangencias de un cilindro son líneas paralelas a W.`,
    `7. SOMBRAS PROYECTADAS: paralelogramos en el plano de apoyo (solo`,
    `   combinaciones de U y V, cero componente W), desplazados en la`,
    `   dirección luz. Relleno plano casi negro o tinta de la paleta. Nada de`,
    `   sombras radiales ni blur en la sombra del suelo.`,
    `8. EXPLOSIONADOS Y APILADOS: componentes alineados al centro (x,y)`,
    `   apilados en el eje W con huecos constantes; la cara top de uno marca`,
    `   la posición de la base del siguiente.`,
    `9. ESTILOS DE REFERENCIA (según la imagen/hint):`,
    `   a) Flat-tone: 3 tonos por sólido + contorno negro uniforme + sombra`,
    `      paralelogramo sólida (estilo sticker/retro-tech).`,
    `   b) Technical line-art: caras blancas, contorno uniforme, TRAMADO`,
    `      (hatching de líneas paralelas al eje U o V) en UNA sola cara para`,
    `      indicar sombra (estilo manual de producto/Sony).`,
    ``,
    `1. PLAN DE CARAS PREVIO. Antes de escribir marcado, define:`,
    `   - Vector de extrusión global E = (dx, dy) en unidades del viewBox, medido`,
    `     de la referencia (p. ej. E = (-16, 20) = hacia abajo-izquierda).`,
    `     TODOS los sólidos de la familia principal usan el MISMO E. Excepción:`,
    `     objetos planos frontales con un canto visible en otro eje (p. ej. el`,
    `     canto derecho de un celular) — se documenta por elemento.`,
    `   - Por cada sólido, lista explícita de caras visibles (top, side-left,`,
    `     side-right, end-cap…). Regla de visibilidad: cara visible ⟺`,
    `     normal_exterior · E > 0.`,
    `2. UNA SILUETA, DOS CAPAS (regla de unidad). Cada sólido se dibuja como UNA`,
    `   sola <path> (silueta completa, contorno cerrado) más ESA MISMA path`,
    `   trasladada por E como capa side debajo. El contorno del top tapa al del`,
    `   side y la cara lateral se lee como un creciente continuo alrededor de la`,
    `   silueta. Prohibido armar un sólido de varias formas con contorno propio`,
    `   (unipse + cola triangular = puntas que no se unen). Los detalles internos`,
    `   (bandas, segmentos, chips) se dibujan ENCIMA del top, recortados a la`,
    `   misma silueta con clipPath. Excepción: contornos internos solo donde la`,
    `   referencia los muestre (líneas de segmentos de un pie chart, anillos).`,
    `3. BARRAS Y BRAZOS: rectángulos redondeados (rx ≈ 25% del ancho de la barra)`,
    `   en dos capas (side trasladado E + top), no polígonos con puntas. El orden`,
    `   de pintado: primero TODOS los sides de la escena, después TODOS los tops,`,
    `   para que no haya costuras entre piezas solapadas.`,
    `4. CILINDROS (monedas, pie charts, perillas): cara top = círculo/elipse;`,
    `   side = banda entre el borde inferior del círculo top y el mismo círculo`,
    `   trasladado E (path con dos arcos de tangencia + líneas de unión).`,
    `   Nunca un círculo desplazado sin banda lateral.`,
    `5. OCCLUSIÓN. Escribe el plan de z-order antes del marcado: qué tapa a cuál`,
    `   y por qué (p. ej. "el marco del celular se dibuja como anillo evenodd`,
    `   ENCIMA del brazo que atraviesa la pantalla"). Las formas que atraviesan`,
    `   otros objetos se recortan con <clipPath> o mask; no se redibujan a ojo.`,
    `6. SOMBRA PROYECTADA en el plano de apoyo, siguiendo la diagonal de E:`,
    `   silueta plana casi negra, sin blur, anclada al objeto que la proyecta.`,
    `7. GEOMETRÍA COMPUTADA > ESTIMADA. Cuando el elemento tenga 4+ aristas o`,
    `   rotaciones, calcula los puntos (a mano con reglas o mentalmente) y`,
    `   escribe los polígonos con esas coordenadas exactas. Un hexágono de brazo`,
    `   isométrico es mejor que un rectángulo con rotate().`,
    ``,
    `## Modo line-art isométrico (monocromo, sin degradados)`,
    `Si la referencia es line-art monocromo (caras blancas, contorno negro, sin degradados):`,
    `- Pinta con var(--ink) / var(--paper). Sin gradientes, mask, blend ni blur.`,
    `- SVG inline con viewBox. Clases: .ln (trazo + relleno), .ink (relleno negro), .mark (trazo sin relleno).`,
    `- Cada caja: 3 polígonos del canon (cara U negra, cara V blanca, tapa W blanca).`,
    `- Mango/tubo: rect rotado al eje de extrusión + elipse de tapa perpendicular.`,
    `- Losetas (teclas): rect rx con matrix(0.866,-0.5,-0.866,-0.5,ox,oy); slab desplazado +7 en oy.`,
    `- Ejemplo de salida correcta: mcp/examples/iso-lupa.html.`,
    `- El validador marcará técnicas ausentes (gradientes, mask, filter...). Es esperado: no las añadas para cumplirlo.`,
    ``,
    `## Fidelidad de réplica (obligatorio)`,
    `La referencia es la especificación exacta, no una inspiración:`,
    `- MIDE antes de generar: aspect-ratio del lienzo; posición de cada elemento`,
    `  en % del lienzo; ángulo de rotación de cada pieza; grosor de contorno`,
    `  relativo (bw ≈ 1.2% del ancho del lienzo); profundidad de extrusión`,
    `  (|E| ≈ 3–6% del ancho del lienzo); tamaños relativos entre piezas.`,
    `- Respeta el mapa de posiciones medido dentro de ±2% del lienzo.`,
    `- NO reorganices la composición, NO añadas ni elimines elementos, NO corrijas`,
    `  el diseño original. Réplica, no reinterpretación.`,
    `- Reproduce exactamente los solapamientos: qué borde pisa a cuál, qué forma`,
    `  sale de qué otra. Si un elemento atraviesa otro, la oclusión debe verse idéntica.`,
    `- Paleta muestreada de la referencia (mismos matices, no "colores parecidos").`,
    ``,
    `## Restricciones de salida`,
    `  - Exactamente un bloque <style> en el head. Sin <link>, sin <script>.`,
    `  - Todas las medidas derivadas de variables vía calc(var(--x) * 1unit).`,
    `  - Ninguna regla con !important salvo los fallback de máscara.`,
    `  - El marcado debe ser HTML válido y profundo: no menos de 60 nodos.`,
    `  - Comentarios de sección en CSS (/*── Cielo ──*/) para legibilidad.`,
    ``,
    `## Objetivo visual`,
    `Composición del boceto con la paleta, temperatura de luz, dirección de la`,
    `iluminación y nivel de detalle de la referencia. Busca profundidad atmosférica:`,
    `planos separados por contraste, no por contorno.`
  );

  return lines.join('\n');
}

export default buildPrompt;
